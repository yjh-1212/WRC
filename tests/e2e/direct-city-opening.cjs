const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require('playwright');
process.env.DATABASE_URL = `file:${path.resolve(__dirname, '../../data/regulatory.db').replace(/\\/g, '/')}`;
const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();
const base = process.env.TARGET_URL || 'http://127.0.0.1:5173';
const password = process.env.TEST_PASSWORD || 'Wrc@2026!';
const adminUsername = `e2e_dco_${Date.now().toString(36)}`;
const artifacts = path.resolve(__dirname, '../../test-results/direct-city-opening');
let workspaceId;
let organizationBefore;
let cityCode;

async function cleanup() {
  const member = await prisma.user.findUnique({ where: { username: adminUsername } });
  const id = workspaceId ?? member?.workspaceId;
  if (!id) return;
  const workspace = await prisma.cityWorkspace.findUnique({ where: { id } });
  assert.equal(workspace.cityCode, cityCode, 'Only remove the city fixture created by this test');
  const users = await prisma.user.findMany({ where: { workspaceId: id }, select: { id: true } });
  const ids = users.map(user => user.id);
  await prisma.refreshToken.deleteMany({ where: { userId: { in: ids } } });
  await prisma.loginLog.deleteMany({ where: { userId: { in: ids } } });
  await prisma.auditLog.deleteMany({ where: { OR: [{ userId: { in: ids } }, { module: 'saas', objectId: id }] } });
  await prisma.userRole.deleteMany({ where: { userId: { in: ids } } });
  await prisma.user.deleteMany({ where: { id: { in: ids } } });
  await prisma.rolePermission.deleteMany({ where: { role: { workspaceId: id } } });
  await prisma.role.deleteMany({ where: { workspaceId: id } });
  await prisma.processNodeDefinition.deleteMany({ where: { processDefinition: { workspaceId: id } } });
  await prisma.processDefinition.deleteMany({ where: { workspaceId: id } });
  await prisma.workspaceInvitation.deleteMany({ where: { workspaceId: id } });
  await prisma.workspaceNotice.deleteMany({ where: { workspaceId: id } });
  await prisma.organization.update({ where: { id: workspace.organizationId }, data: { workspaceId: null, ...(organizationBefore ? { name: organizationBefore.name } : {}) } });
  await prisma.cityWorkspace.delete({ where: { id } });
  if (!organizationBefore) await prisma.organization.delete({ where: { id: workspace.organizationId } });
}

(async () => {
  fs.mkdirSync(artifacts, { recursive: true });
  const browser = await chromium.launch({ headless: process.env.PW_HEADLESS === 'true' });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/login`);
    await page.getByLabel('账号', { exact: true }).fill('admin');
    await page.getByLabel('密码', { exact: true }).fill(password);
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.waitForURL('**/province/overview');
    assert.equal(await page.getByText('待审核申请', { exact: true }).count(), 0);
    const data = await page.evaluate(async () => {
      const headers = { authorization: `Bearer ${sessionStorage.getItem('wrc-access-token')}` };
      const get = async url => (await (await fetch(`/api${url}`, { headers })).json()).data;
      return { options: await get('/saas/workspaces/options'), menus: await get('/auth/menus') };
    });
    assert(!JSON.stringify(data.menus).includes('/province/applications'));
    const city = data.options.cities.find(item => !item.opened);
    assert(city, 'Need an unopened city for the isolated fixture');
    cityCode = city.code;
    organizationBefore = await prisma.organization.findUnique({ where: { code: `CITY-${city.code}` } });
    await page.goto(`${base}/province/applications`);
    await page.waitForURL('**/province/workspaces');
    await page.getByRole('button', { name: '开通城市', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('button', { name: '确认开通', exact: true }).click();
    await dialog.getByText('请选择开通城市', { exact: true }).waitFor();
    await dialog.getByRole('combobox', { name: '开通城市', exact: true }).click();
    await page.getByRole('option', { name: city.name, exact: true }).click();
    await dialog.getByRole('textbox', { name: '联系人', exact: true }).fill('开通联系人');
    await dialog.getByRole('textbox', { name: '联系电话', exact: true }).fill('0531-88001234');
    await dialog.getByRole('textbox', { name: '管理员姓名', exact: true }).fill('地市管理员');
    await dialog.getByRole('textbox', { name: '管理员账号', exact: true }).fill('admin');
    await dialog.getByLabel('初始密码', { exact: true }).fill(password);
    await dialog.getByRole('textbox', { name: '线下申请依据', exact: true }).fill('线下授权函 SD-E2E-DIRECT');
    await dialog.getByRole('button', { name: '确认开通', exact: true }).click();
    await dialog.getByRole('alert').filter({ hasText: '管理员账号已存在' }).waitFor();
    assert.equal(await dialog.getByRole('textbox', { name: '联系电话', exact: true }).inputValue(), '0531-88001234');
    await dialog.getByRole('textbox', { name: '管理员账号', exact: true }).fill(adminUsername);
    await page.screenshot({ path: path.join(artifacts, 'opening-form.png'), fullPage: true });
    const opened = page.waitForResponse(response => response.url().endsWith('/api/saas/workspaces') && response.request().method() === 'POST' && response.status() === 201);
    await dialog.getByRole('button', { name: '确认开通', exact: true }).click();
    workspaceId = (await (await opened).json()).data.workspace.id;
    await dialog.getByText(`${city.name}已开通，管理员可直接登录`, { exact: true }).waitFor();
    await page.screenshot({ path: path.join(artifacts, 'opening-success.png'), fullPage: true });
    await dialog.getByRole('button', { name: '关闭', exact: true }).click();
    await page.reload();
    await page.locator('.city-identity strong').filter({ hasText: city.name }).waitFor();
    const cityPage = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    cityPage.on('pageerror', error => errors.push(error.message));
    await cityPage.goto(`${base}/login`);
    await cityPage.getByLabel('账号', { exact: true }).fill(adminUsername);
    await cityPage.getByLabel('密码', { exact: true }).fill(password);
    await cityPage.getByRole('button', { name: '登录', exact: true }).click();
    await cityPage.waitForURL('**/regulatory/overview');
    await cityPage.locator('.dashboard-page').waitFor();
    await cityPage.goto(`${base}/city/workspace?view=requests`);
    await cityPage.getByText('功能调整、授权续期和管理员变更，请线下联系省级管理员办理。', { exact: true }).waitFor();
    assert.equal(await cityPage.getByRole('button', { name: '提交变更申请', exact: true }).count(), 0);
    const publicPage = await browser.newPage();
    await publicPage.goto(`${base}/apply`);
    await publicPage.getByRole('heading', { name: '地市平台开通', exact: true }).waitFor();
    assert.equal(await publicPage.locator('form').count(), 0);
    assert.deepEqual(errors, []);
    console.log('PASS: no application review menu; direct opening validation and duplicate recovery; persisted city; immediate administrator login; offline authorization notice; public application form retired.');
  } finally {
    await browser.close();
    await cleanup();
    await prisma.$disconnect();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
